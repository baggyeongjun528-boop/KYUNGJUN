/**
 * Generate synthetic historical series for charts based on current scenario.
 */
export function generateChartHistory(metrics: MarketMetrics): PricePoint[] {
  const points: PricePoint[] = [];
  const basePrice = metrics.nasdaq100.price;
  const baseVix = metrics.vix.current;
  const days = 30;

  for (let i = days; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const dateLabel = `${d.getMonth() + 1}/${d.getDate()}`;
    
    // Simulate trend leading up to current scenario
    const progress = (days - i) / days;
    let factor = 1.0;
    let vixFactor = 1.0;
    let breadth = 50;

    if (metrics.dropFromHighPercent && metrics.dropFromHighPercent < -15) {
      // Crash curve
      factor = 1.0 + (metrics.dropFromHighPercent / 100) * (1 - Math.sin(progress * Math.PI * 0.5));
      vixFactor = 15 + (metrics.vix.highToday - 15) * Math.sin(progress * Math.PI * 0.8);
      breadth = Math.max(8, 60 - progress * 50);
    } else if (metrics.dropFromHighPercent && metrics.dropFromHighPercent < -5) {
      factor = 1.0 - (progress * 0.07);
      vixFactor = 14 + progress * (baseVix - 14);
      breadth = Math.max(20, 55 - progress * 30);
    } else {
      factor = 1.0 - (1 - progress) * 0.03 + (Math.sin(i) * 0.008);
      vixFactor = baseVix + Math.cos(i) * 1.2;
      breadth = 60 + Math.sin(i) * 5;
    }

    const dayPrice = i === 0 ? basePrice : basePrice * factor;
    const dayVix = i === 0 ? baseVix : Math.max(12, vixFactor);
    const dma20 = dayPrice * 1.015;
    const dma50 = dayPrice * 1.04;
    const dma200 = dayPrice * 1.08;
    const vwap = dayPrice * (metrics.nasdaq100.aboveVwap ? 0.992 : 1.008);
    const volume = 1000000 * (1 + (i === 0 ? metrics.volumeRatioVsAverage : (1 + Math.random() * 0.4)));

    points.push({
      time: dateLabel,
      price: Math.round(dayPrice),
      dma20: Math.round(dma20),
      dma50: Math.round(dma50),
      dma200: Math.round(dma200),
      vwap: Math.round(vwap),
      volume: Math.round(volume),
      vix: Number(dayVix.toFixed(1)),
      breadth50: Number(breadth.toFixed(1)),
      rsi: Number((30 + progress * 25 + Math.sin(i) * 8).toFixed(1)),
    });
  }

  return points;
}
